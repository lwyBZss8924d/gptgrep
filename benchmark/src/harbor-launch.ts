import { spawn } from "node:child_process";
import { lstat, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { assertTaskAdmitted, closed, dependencyProjection, loadAdmission, readExactJson, verifyPin,
  verifyRequiredPreprocessing, type AdmissionReference, type Pin } from "./availability";
import { canonical, digest, fileHash, physicalPath, requireStorage, sha256, within } from "./io";

export interface HarborLaunchOptions { admission: AdmissionReference; outputDir: string; }
interface ExportIndex {
  schema: "gptgrep.harbor-export.v1"; status: "generated_pending_acceptance";
  assessmentSha256: string; generation: number; releaseRevision: string; profileId: string; arm: string;
  tasks: Array<{ taskId: string; directory: string; files: Array<{ path: string; sha256: string }> }>;
}
interface ExportAcceptance { schema: "gptgrep.harbor-export-acceptance.v1"; status: "accepted"; generated: Pin; review: Pin; }
interface RuntimeAcceptance {
  schema: "gptgrep.harbor-runtime-acceptance.v1"; status: "qualified";
  cliContract: "harbor-run-path-agent-job-name-v1";
  transport: "codex-auth-supervisor-direct-harbor"; environment: "linux";
  python: Pin; supervisor: Pin; harbor: Pin; authConfig: Pin; qualification: Pin;
  agent: string; runId: string; deadlineSeconds: number;
}

/** A digest is required; mutable tags and shell/TOML syntax are not image pins. */
export function validImmutableImage(value: unknown): value is string {
  return typeof value === "string" && value.length <= 512 &&
    /^(?:sha256:[a-f0-9]{64}|[A-Za-z0-9][A-Za-z0-9._/:\-]*@sha256:[a-f0-9]{64})$/.test(value);
}

/** Inventory every regular byte, including verifier material, without reading its content. */
export async function indexTaskFiles(directory: string): Promise<Array<{ path: string; sha256: string }>> {
  await physicalPath(directory);
  const files: Array<{ path: string; sha256: string }> = [];
  const walk = async (root: string, prefix: string) => {
    for (const name of (await readdir(root)).sort()) {
      const path = join(root, name), relative = prefix ? `${prefix}/${name}` : name, info = await lstat(path);
      if (info.isSymbolicLink()) throw new Error("Export contains a symlink");
      if (info.isDirectory()) await walk(path, relative);
      else if (info.isFile()) files.push({ path: relative, sha256: await fileHash(path) });
      else throw new Error("Export contains a special file");
    }
  };
  await walk(directory, ""); return files;
}

/** No process, auth request or container action occurs in this preflight. */
async function inspectHarbor(options: HarborLaunchOptions) {
  closed(options, ["admission", "outputDir"], "Harbor launch config");
  const admission = await loadAdmission(options.admission, options.outputDir);
  const { acceptance, assessment } = admission;
  if (!acceptance.harborExport || !acceptance.runtime) throw new Error("Accepted runnable export and qualified runtime are required");
  await verifyPin(acceptance.harborExport); await verifyPin(acceptance.runtime);
  const exported = await readExactJson<ExportAcceptance>(acceptance.harborExport.path);
  closed(exported, ["schema", "status", "generated", "review"], "export acceptance");
  if (exported.schema !== "gptgrep.harbor-export-acceptance.v1" || exported.status !== "accepted") throw new Error("Export has not been independently accepted");
  await verifyPin(exported.generated); await verifyPin(exported.review);
  const exportReview = await readExactJson(exported.review.path);
  closed(exportReview, ["schema", "status", "generated"], "export review");
  if (exportReview.schema !== "gptgrep.harbor-export-review.v1" || exportReview.status !== "accepted" || canonical(exportReview.generated) !== canonical(exported.generated)) throw new Error("Export review does not accept these exact generated bytes");
  const index = await readExactJson<ExportIndex>(exported.generated.path);
  closed(index, ["schema", "status", "assessmentSha256", "generation", "releaseRevision", "profileId", "arm", "tasks"], "export index");
  if (index.schema !== "gptgrep.harbor-export.v1" || index.status !== "generated_pending_acceptance" || index.assessmentSha256 !== acceptance.assessment.sha256 ||
      index.generation !== assessment.generation || index.releaseRevision !== assessment.release.revision || index.profileId !== options.admission.profileId) throw new Error("Export assessment/profile is stale or mismatched");
  const ids = index.tasks.map(t => t.taskId);
  if (!ids.length || new Set(ids).size !== ids.length || canonical([...ids].sort()) !== canonical([...acceptance.taskIds].sort())) throw new Error("Launched task set must equal the accepted export selection");
  const root = resolve(exported.generated.path, "..");
  const expectedEntries = [basename(exported.generated.path), ...index.tasks.map(t => basename(t.directory))].sort();
  if (canonical((await readdir(root)).sort()) !== canonical(expectedEntries)) throw new Error("Export root contains unaccepted tasks or files");
  let requiresPairedController = false;
  for (const entry of index.tasks) {
    closed(entry, ["taskId", "directory", "files"], "export task entry");
    if (resolve(entry.directory, "..") !== root || !within(root, entry.directory)) throw new Error("Export task escapes the accepted root");
    if (canonical(await indexTaskFiles(entry.directory)) !== canonical(entry.files)) throw new Error("Generated task bytes changed");
    const requiredFiles = ["adapter-manifest.json", "instruction.md", "task.toml", "environment/Dockerfile", "environment/context.json",
      "tests/verify.py", "tests/checks.py", "tests/pyproject.toml", "tests/test.sh", "tests/Dockerfile", "tests/upstream_evaluate.py", "tests/gold.jsonl", "tests/expected.json"];
    if (requiredFiles.some(path => !entry.files.some(file => file.path === path))) throw new Error("Accepted export is missing runnable task material");
    const manifest = await readExactJson(join(entry.directory, "adapter-manifest.json"));
    const dependency = assessment.release.tasks.find(t => t.id === entry.taskId);
    if (!dependency || manifest.schema !== "gptgrep.xl-harbor-task.v1" || manifest.task_id !== entry.taskId || manifest.arm !== index.arm ||
        manifest.source_revision !== assessment.release.revision || digest(manifest.source_file_hashes) !== digest(assessment.release.fileHashes) ||
        manifest.context_id !== dependency.contextId || manifest.group_id !== dependency.groupId ||
        manifest.availability?.assessmentSha256 !== acceptance.assessment.sha256 || manifest.availability.generation !== assessment.generation ||
        manifest.availability.assessmentRevision !== assessment.revision || manifest.availability.dependencySha256 !== assessment.dependencySha256 ||
        manifest.availability.profileId !== index.profileId || manifest.availability.taskDependencySha256 !== digest(dependencyProjection(dependency))) throw new Error("Generated manifest identity mismatch");
    let workspace = "/app";
    if (manifest.execution !== undefined) {
      closed(manifest.execution, ["kind", "image", "workspace"], "generated execution binding");
      if (manifest.execution.kind !== "prebuilt-bind" || !validImmutableImage(manifest.execution.image) || manifest.execution.workspace !== "/app/task") throw new Error("Invalid generated prebuilt execution binding");
      const config = Bun.TOML.parse(await readFile(join(entry.directory, "task.toml"), "utf8")) as { environment?: { docker_image?: unknown } };
      if (config.environment?.docker_image !== manifest.execution.image) throw new Error("Prebuilt task image differs from its generated binding");
      workspace = manifest.execution.workspace;
      requiresPairedController = true;
    }
    const context = await readExactJson(join(entry.directory, "environment/context.json"));
    closed(context, ["schema", "task_id", "context_id", "corpus_sha256", "documents"], "generated context");
    if (context.schema !== "gptgrep.xl-reader-context.v1" || context.task_id !== dependency.id || context.context_id !== dependency.contextId || canonical(context.documents.map((d: any) => d.document_id).sort()) !== canonical([...dependency.contextDocumentIds].sort())) throw new Error("Generated context is narrowed or foreign");
    const raw = [];
    for (const document of context.documents) {
      closed(document, ["document_id", "path", "sha256", "page_count"], "generated document");
      const prefix = `${workspace}/documents/`;
      if (typeof document.path !== "string" || !document.path.startsWith(prefix) || basename(document.path) !== document.path.slice(prefix.length)) throw new Error("Unsafe generated RAW path");
      const path = join(entry.directory, "environment/documents", basename(document.path));
      if (await fileHash(path) !== document.sha256 || document.page_count !== assessment.release.documents.find(d => d.documentId === document.document_id)?.pageCount) throw new Error("Generated RAW identity changed");
      raw.push({ documentId: document.document_id, sha256: document.sha256 });
    }
    const corpus = sha256(JSON.stringify(raw.map(d => ({ document_id: d.documentId, sha256: d.sha256 })).sort((a, b) => a.document_id.localeCompare(b.document_id))));
    if (context.corpus_sha256 !== corpus || manifest.corpus_sha256 !== corpus) throw new Error("Generated corpus digest mismatch");
    const record = assertTaskAdmitted(admission, dependency, index.arm, raw);
    if (manifest.availability.profileSha256 !== record.armAvailability[index.profileId]!.profileSha256) throw new Error("Generated profile changed");
    const preparedFiles: Array<{ relativePath: string; sha256: string }> = [];
    for (const artifact of manifest.prepared_artifacts ?? []) {
      if (artifact.scope !== "tool" && canonical([...(manifest.prepared_context_document_ids ?? [])].sort()) !== canonical([...dependency.contextDocumentIds].sort())) throw new Error("Generated preprocessing context differs from task");
      const path = resolve(entry.directory, "environment/prepared", artifact.relative_path);
      if (!within(join(entry.directory, "environment/prepared"), path) || await fileHash(path) !== artifact.sha256) throw new Error("Generated preprocessing changed");
      preparedFiles.push({ relativePath: artifact.relative_path, sha256: artifact.sha256 });
    }
    await verifyRequiredPreprocessing(admission, [dependency], preparedFiles);
  }
  // This older --path/--agent route cannot supply the exact owner container job.
  if (requiresPairedController) throw new Error("Prebuilt bind exports require the paired controller v2 and its exact container owner admission");
  const runtime = await readExactJson<RuntimeAcceptance>(acceptance.runtime.path);
  closed(runtime, ["schema", "status", "cliContract", "transport", "environment", "python", "supervisor", "harbor", "authConfig", "qualification", "agent", "runId", "deadlineSeconds"], "runtime acceptance");
  if (runtime.schema !== "gptgrep.harbor-runtime-acceptance.v1" || runtime.status !== "qualified" || runtime.cliContract !== "harbor-run-path-agent-job-name-v1" ||
      runtime.transport !== "codex-auth-supervisor-direct-harbor" || runtime.environment !== "linux" ||
      !validHarborAgent(runtime.agent) || !/^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,100}$/.test(runtime.runId) ||
      !Number.isSafeInteger(runtime.deadlineSeconds) || runtime.deadlineSeconds < 1 || runtime.deadlineSeconds > 86400) throw new Error("Runtime is not qualified for the closed launch contract");
  for (const pin of [runtime.python, runtime.supervisor, runtime.harbor, runtime.authConfig, runtime.qualification]) await verifyPin(pin);
  const qualification = await readExactJson(runtime.qualification.path);
  closed(qualification, ["schema", "status", "runtimeContractSha256"], "runtime qualification");
  const { qualification: qualificationPin, ...runtimeContract } = runtime;
  if (qualification.schema !== "gptgrep.harbor-runtime-qualification.v1" || qualification.status !== "accepted" || qualification.runtimeContractSha256 !== digest(runtimeContract)) throw new Error("Runtime qualification does not accept this exact launch contract");
  // Qualification must establish these exact Harbor flags and Linux/agent behavior.
  // No qualified production receipt is supplied by this source implementation.
  const argv = [runtime.python.path, runtime.supervisor.path, "--config", runtime.authConfig.path,
    "run", "--role", "harbor", "--run-id", runtime.runId, "--lease", "exclusive", "--deadline-seconds", String(runtime.deadlineSeconds),
    "--harbor-job-label", `gptgrep.auth-job=${runtime.runId}`, "--pre-refresh", "never", "--live-request-attempted", "unknown", "--stdin", "null", "--",
    runtime.harbor.path, "run", "--path", root, "--agent", runtime.agent, "--job-name", runtime.runId];
  return { schema: "gptgrep.harbor-preflight.v1", status: "admitted", taskIds: ids, arm: index.arm,
    assessmentSha256: acceptance.assessment.sha256, generation: assessment.generation, argv };
}

/** Harbor accepts a registered name or an explicit Python module:Class route. */
export function validHarborAgent(value: unknown): value is string {
  return typeof value === "string" && value.length <= 200 &&
    (/^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,100}$/.test(value) ||
     /^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*:[A-Za-z_]\w*$/.test(value));
}

async function recordDenial(options: HarborLaunchOptions, error: unknown, executionMode: "live" | "test" | "preflight") {
  await mkdir(options.outputDir, { recursive: true });
  await writeFile(join(options.outputDir, `prelaunch-denial-${crypto.randomUUID()}.json`), JSON.stringify({
    schema: "gptgrep.harbor-prelaunch-denial.v1", executionMode, status: "denied_before_dispatch", processStarted: false,
    measurement: null, reason: error instanceof Error ? error.message : "Admission failed",
  }) + "\n", { flag: "wx", mode: 0o600 });
}

export async function harborPreflight(options: HarborLaunchOptions) {
  await requireStorage(options.outputDir);
  try { return await inspectHarbor(options); }
  catch (error) { await recordDenial(options, error, "preflight"); throw error; }
}

async function dispatch(options: HarborLaunchOptions, launch: (argv: string[]) => Promise<number>, executionMode: "live" | "test") {
  await requireStorage(options.outputDir);
  let ready: Awaited<ReturnType<typeof inspectHarbor>>;
  try {
    await inspectHarbor(options);
    // Re-read current selection, acceptance, complete exported bytes and runtime just before creation.
    ready = await inspectHarbor(options);
  } catch (error) {
    await recordDenial(options, error, executionMode);
    throw error;
  }
  const exitCode = await launch(ready.argv);
  return { schema: "gptgrep.harbor-dispatch.v1", executionMode, status: "dispatched", exitCode, taskIds: ready.taskIds };
}

export async function runHarbor(options: HarborLaunchOptions) {
  return dispatch(options, argv => new Promise<number>((resolveExit, reject) => {
    const child = spawn(argv[0]!, argv.slice(1), { stdio: ["ignore", "inherit", "inherit"], shell: false });
    child.once("error", reject); child.once("exit", (code, signal) => signal ? reject(new Error("Supervisor terminated by signal")) : resolveExit(code ?? 1));
  }), "live");
}

/** Synthetic seam only; results are explicitly test evidence and cannot qualify a runtime. */
export async function runHarborForTest(options: HarborLaunchOptions, launch: (argv: string[]) => Promise<number>) {
  return dispatch(options, launch, "test");
}
